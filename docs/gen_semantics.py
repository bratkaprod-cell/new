wb = Workbook()
hdr_fill = PatternFill("solid", fgColor="FFD400")
hdr_font = Font(bold=True, size=11)
thin = Border(*[Side(style="thin", color="CCCCCC")]*4)

def sheet(name, rows, note):
    ws = wb.create_sheet(name)
    ws.append([note])
    ws["A1"].font = Font(italic=True, size=9, color="666666")
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=6)
    headers = ["Запрос", "Частотность, показов/мес (оценка)", "Конкуренция в Директе", "Теплота", "Посадочная страница", "Брать в кампанию 6000 ₽?"]
    ws.append(headers)
    for c in range(1, 7):
        cell = ws.cell(row=2, column=c)
        cell.fill = hdr_fill; cell.font = hdr_font; cell.border = thin
    for r in rows:
        ws.append(list(r))
    widths = [52, 18, 14, 8, 18, 32]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for row in ws.iter_rows(min_row=3):
        for cell in row:
            cell.border = thin
            cell.alignment = Alignment(vertical="top", wrap_text=True)
    ws.freeze_panes = "A3"
    return ws

