const len = (s) => [...s].length;
function validate() {
  const errs = [];
  const seen = new Set();
  for (const c of CAMPAIGNS)
    for (const g of c.groups) {
      if (len(g.t1) > 56) errs.push(`T1 >56: ${g.name} (${len(g.t1)})`);
      if (len(g.t2) > 30) errs.push(`T2 >30: ${g.name} (${len(g.t2)})`);
      if (len(g.text) > 81) errs.push(`Text >81: ${g.name} (${len(g.text)})`);
      if (len(g.slug) > 20) errs.push(`DisplayLink >20: ${g.name}`);
      for (const [k] of g.keys) {
        const base = k.split(' -')[0].trim();
        if (!base) errs.push(`пустой ключ в ${g.name}`);
        if (seen.has(base)) errs.push(`дубль ключа: ${base}`);
        seen.add(base);
        if (base.split(/\s+/).length > 7) errs.push(`ключ >7 слов: ${base}`);
      }
    }
  const st = SITELINK_TITLES.split('||');
  if (st.some((t) => len(t) > 30)) errs.push('быстрая ссылка >30');
  if (st.reduce((a, t) => a + len(t), 0) > 66) errs.push('сумма быстрых ссылок >66');
  if (CALLOUTS.split('||').some((t) => len(t) > 25)) errs.push('уточнение >25');
  return errs;
}

