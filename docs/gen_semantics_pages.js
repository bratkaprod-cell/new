// ---------- генерация ----------
function round5(n) { return Math.max(5, Math.round(n / 5) * 5); }

function competition(freq) {
  if (freq >= 300) return 'высокая';
  if (freq >= 60) return 'средняя';
  return 'низкая';
}

function priority(heat, freq, type) {
  if (heat === '🔥' && freq >= 20) return '1 — ядро (горячий)';
  if (heat === '🔥') return '2 — расширение (горячий НЧ)';
  if (heat === '●' && type === 'коммерческий') return '1 — ядро (коммерческий)';
  if (heat === '●') return '2 — расширение';
  return '3 — тест/SEO (холодный)';
}

function buildGroup(page) {
  const cms = CMS[page];
  const rows = [];
  const seen = new Set();
  const add = (query, freq, heat, type, comment) => {
    const q = query.replace(/\s+/g, ' ').trim().toLowerCase();
    if (seen.has(q)) return;
    seen.add(q);
    rows.push([q, round5(freq), competition(round5(freq)), heat, type, priority(heat, round5(freq), type), comment || '']);
  };

  const BASE_FREQ = 420; // «лечение сайта X от вирусов» для WP ≈ 420/мес

  for (const [tpl, k, heat] of BASES) {
    const freq = BASE_FREQ * k * cms.factor;
    add(tpl.replace('X', cms.tail), freq, heat, 'базовый', '');
    // альтернативные написания CMS — только для сильных баз
    if (k >= 0.6) {
      for (const alt of cms.alts) {
        add(tpl.replace('X', alt), freq * 0.35, heat, 'базовый (alt-написание)', '');
      }
    }
    // коммерческие модификаторы — к базам услуг
    if (k >= 0.4) {
      for (const [mod, mk, mheat, mtype] of MODS) {
        add(tpl.replace('X', cms.tail) + ' ' + mod, freq * mk, mheat, mtype, '');
      }
    }
    // горячие хвосты — к горячим базам
    if (heat === '🔥') {
      for (const [tail, tk, theat] of HOT_TAILS) {
        add(tpl.replace('X', cms.tail) + ' ' + tail, freq * tk, theat, 'горячий хвост', '');
      }
    }
  }
  for (const [q, f, heat, type, comment] of cms.specific) {
    add(q, f, heat, type, comment);
  }
  rows.sort((a, b) => b[1] - a[1]);
  return rows;
}

